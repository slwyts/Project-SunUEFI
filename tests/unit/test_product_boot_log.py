"""Execute the actual native product boot log renderer, no device operations."""
import platform
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
HOST_PROCESSOR_BIND = 'AArch64' if platform.machine() in ('aarch64', 'arm64') else 'X64'
TOOLCHAIN = Path(os.environ.get('SUNUEFI_TOOLCHAIN_ROOT', ROOT / 'build/host-tools/usr'))
INC = ROOT / 'upstream/Mu-Silicium/Mu_Basecore/MdePkg/Include'
SOURCE = ROOT / 'uefi/core/PianoProductBootLog.c'
SPLASH = ROOT / 'uefi/components/product-support/Library/ProductBootManagerLib/ProductSplash.c'
sys.path.insert(0, str(ROOT / 'tools'))
import prepare_product_console as console


class ProductBootLogTests(unittest.TestCase):
    def glyphs(self, directory):
        # PianoChineseGlyphs.h generated by the product console preparation, from pinned strings
        root = Path(directory)
        shutil.copytree(ROOT / console.SOURCE, root / console.SOURCE)
        for name in console.STRINGS:
            path = root / console.PKG / name
            path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(ROOT / console.PKG / name, path)
        (root / console.CONSOLE).mkdir(parents=True, exist_ok=True)
        try:
            console.prepare(root, apply=True)
        except ImportError as error:
            self.skipTest('freetype-py unavailable: ' + str(error))
        except ValueError as error:
            if not str(error).startswith('Install fonts-noto-cjk'):
                raise
            self.skipTest(str(error))
        return root / console.CONSOLE

    def test_actual_pixels_status_elapsed_and_failure_fences(self):
        output = ROOT / 'build/previews/product-splash'
        output.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix='piano-bootlog-') as directory:
            executable = Path(directory) / 'bootlog'
            generated = self.glyphs(Path(directory) / 'console')
            subprocess.run(['cc', '-std=gnu11', '-Wall', '-Wextra', '-Werror',
                '-Wno-misleading-indentation', '-fshort-wchar', '-fsanitize=address,undefined',
                '-fno-pie', '-no-pie', '-I' + str(INC), '-I' + str(INC / HOST_PROCESSOR_BIND),'-I'+str(generated),
                str(ROOT / 'tests/native/PianoProductBootLogTest.c'), str(SOURCE), str(SPLASH),
                '-o', str(executable)], check=True)
            run = subprocess.run([str(executable), str(output / 'product-bootlog-3200x2136.ppm')],
                capture_output=True, text=True, env={**os.environ, 'ASAN_OPTIONS': 'detect_leaks=1'})
            self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
            print(run.stdout.strip())
            subprocess.run([str(TOOLCHAIN/'bin/clang'),
                '--target=aarch64-windows-msvc', '-ffreestanding', '-fshort-wchar',
                '-fsyntax-only', '-Wall', '-Wextra', '-Werror', '-I' + str(INC),
                '-I' + str(INC / 'AArch64'),'-I'+str(generated),str(SOURCE)], check=True)


if __name__ == '__main__':
    unittest.main()
